    public LocalDate getFecha() {
        int año = getAño();
        int mes = getMes();
        int dia = getDia();
        
        if (año != -1 && mes != 0 && dia != -1) {
            return LocalDate.of(año, mes, dia);
        }
        return null;
    }
    
